// YakYak i18n — translates the app's own UI chrome (buttons, headings,
// labels, hints) to match the learner's native language. This is SEPARATE
// from the AI-generated lesson content, which already asks Claude to
// respond in the learner's native language on its own.
//
// Usage: call setLocale(profile.native_language) once you have a profile
// (or as soon as a native-language chip is tapped during onboarding), then
// use t('some.key') anywhere in page templates. langDisplay(code) and
// nativeLangDisplay(englishName) give localized language names for UI
// only — API calls to edge functions always keep using langByCode(code)
// .name (English), since that's what the AI prompts are written against.

const LANG_CODE_MAP = { English: 'en', Spanish: 'es', Portuguese: 'pt', French: 'fr', German: 'de', Mandarin: 'zh' };
let _locale = 'en';
function setLocale(nativeLanguage) {
  _locale = LANG_CODE_MAP[nativeLanguage] || 'en';
}

function t(key, vars) {
  const dict = STRINGS[_locale] || STRINGS.en;
  let str = (dict && dict[key] !== undefined) ? dict[key] : (STRINGS.en[key] !== undefined ? STRINGS.en[key] : key);
  if (vars) {
    Object.keys(vars).forEach(k => { str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]); });
  }
  return str;
}

